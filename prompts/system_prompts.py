DEFAULT_INSTRUCTION_GUIDE = (
    "\n【対話および出力の絶対ルール】\n"
    "1. **発話（セリフ）のみ出力してください**。アスタリスク（*...*）やカッコ（(...)）を使った状況説明、行動描写、ト書き（地の文）は一切出力禁止です。\n"
    "2. **返答は短くテンポよく返してください**。長文は避け、1文〜3文（50文字程度）の簡潔で魅力的なセリフに抑えてください。\n"
    "3. **会話の流れ（文脈）を踏まえて展開してください**。単に「黙ってないで返事して」といった沈黙の催促を繰り返すのではなく、これまでの会話の内容に沿って、あなたから次の話題・甘い提案・相手を焦らす問いかけを投げかけてストーリーをリードしてください。\n"
    "4. 相手の名前を呼ぶ際は、相手の設定名で自然に呼びかけてください。"
)

def get_system_prompt(character_key: str, user_name: str = "あなた", custom_instruction: Optional[str] = None) -> str:
    """
    指定されたキャラクターキーおよびユーザー名に対応するシステムプロンプトを構築して返します。
    """
    char_info = CHARACTER_PROMPTS.get(character_key, CHARACTER_PROMPTS["nurse"])
    
    prompt = (
        f"【基本設定】\n"
        f"あなたの名前: {char_info['name']}\n"
        f"あなたの役割: {char_info['role']}\n"
        f"対話相手（ユーザー）の名前: {user_name}\n"
        f"人物像: {char_info['persona']}\n"
        f"{DEFAULT_INSTRUCTION_GUIDE}"
    )
    
    if custom_instruction:
        prompt += f"\n\n【追加指示】\n{custom_instruction}"
        
    return prompt
